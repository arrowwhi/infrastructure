package masking

import "regexp"

// rule описывает отдельное правило маскирования.
// Определяет набор регулярных выражений для поиска совпадений и замены найденных данных,
// а также функцию маскирования, если требуется специальная логика обработки.
type rule struct {
	froms  []*regexp.Regexp // Скомпилированные регулярные выражения для метчинга входных значений.
	to     *regexp.Regexp   // Скомпилированное регулярное выражение для подстановки замещающего значения.
	maskFn                  // Функция маскирования, применяемая к входным данным.  Если не определена (nil), используется замена через регулярное выражение (тип правила [Const]).
	mv     []byte           // Значение, которым будет заменено исходное значение в случае отсутствия функции маскирования (тип правила [Const])
}

// getDefaultMaskFn возвращает функцию маскирования c подстановкой значения маскирования
// в соответствии с паттерном подстановки.
//
// Используется в случаях, когда тип правила [Const] (подстановка значения маскирования в соответствии с паттерном подстановки r.to)
func (r rule) getDefaultMaskFn() maskFn {
	return func(b []byte) []byte {
		return r.to.ReplaceAll(b, r.mv)
	}
}
